def uri_cases() -> list[dict[str, object]]:
    assert len(URI_TEXTS) == len(set(URI_TEXTS)), "duplicate URI texts"  # noqa: S101
    return [{"units": _units(text)} for text in URI_TEXTS]


def yaml_cases() -> list[dict[str, object]]:
    names = [name for name, _ in CASES + UNIT_CASES]
    assert len(names) == len(set(names)), "duplicate case names"  # noqa: S101
    cases: list[dict[str, object]] = [{"name": name, "text": text} for name, text in CASES]
    return cases + [{"name": name, "units": _units(text)} for name, text in UNIT_CASES]
